func withTempWorkDir(t *testing.T) string {
	t.Helper()

	tmpDir := t.TempDir()
	oldWd, err := os.Getwd()
	if err != nil {
		t.Fatalf("Getwd() error = %v", err)
	}
	t.Cleanup(func() {
		_ = os.Chdir(oldWd)
	})

	if err := os.Chdir(tmpDir); err != nil {
		t.Fatalf("Chdir() error = %v", err)
	}

	return tmpDir
}

func TestHandlerTemplateLeavesSuccessfulNoResponseToLogic(t *testing.T) {
	templatePath := filepath.Join("..", "..", "..", "..", ".template", "go-zero", "api", "handler.tpl")
	data, err := os.ReadFile(templatePath)
	if err != nil {
		t.Fatalf("ReadFile(%s) error = %v", templatePath, err)
	}

	if strings.Contains(string(data), "httpx.Ok(w)") {
		t.Fatalf("no-response handlers must not overwrite status or body written by logic:\n%s", data)
	}
}

func TestCleanHandlersDirKeepsHandlersWhenRewriteHandlerFalse(t *testing.T) {
	withTempWorkDir(t)

	handlerPath := filepath.Join("internal", "handler", "user", "custom.go")
	if err := os.MkdirAll(filepath.Dir(handlerPath), 0o755); err != nil {
		t.Fatalf("MkdirAll() error = %v", err)
	}
	if err := os.WriteFile(handlerPath, []byte("package user\n"), 0o644); err != nil {
		t.Fatalf("WriteFile() error = %v", err)
	}

	apiFile := filepath.Join("desc", "api", "user.api")
	apiSpecMap := map[string]*spec.ApiSpec{
		apiFile: {
			Service: spec.Service{
				Groups: []spec.Group{
					{
						Annotation: spec.Annotation{
							Properties: map[string]string{
								"group":           "user",
								"rewrite_handler": "false",
							},
						},
					},
				},
			},
		},
	}

	ja := &PzeroApi{}
	if err := ja.cleanHandlersDir([]string{apiFile}, apiSpecMap); err != nil {
		t.Fatalf("cleanHandlersDir() error = %v", err)
	}

	if _, err := os.Stat(handlerPath); err != nil {
		t.Fatalf("cleanHandlersDir() should keep handler when rewrite_handler is false, stat err = %v", err)
	}
}

func TestCleanHandlersDirPreservesTestsWhenRewriteHandlerTrue(t *testing.T) {
	withTempWorkDir(t)

	handlerDir := filepath.Join("internal", "handler", "user")
	if err := os.MkdirAll(handlerDir, 0o755); err != nil {
		t.Fatalf("MkdirAll() error = %v", err)
	}

	handlerPath := filepath.Join(handlerDir, "user.go")
	testPath := filepath.Join(handlerDir, "user_test.go")
	for path, content := range map[string][]byte{
		handlerPath: []byte("// Code generated by goctl. DO NOT EDIT.\npackage user\n"),
		testPath:    []byte("package user\n"),
	} {
		if err := os.WriteFile(path, content, 0o644); err != nil {
			t.Fatalf("WriteFile(%q) error = %v", path, err)
		}
	}

	apiFile := filepath.Join("desc", "api", "user.api")
	apiSpecMap := map[string]*spec.ApiSpec{
		apiFile: {
			Service: spec.Service{
				Groups: []spec.Group{
					{
						Annotation: spec.Annotation{
							Properties: map[string]string{
								"group": "user",
							},
						},
					},
				},
			},
		},
	}

	ja := &PzeroApi{}
	if err := ja.cleanHandlersDir([]string{apiFile}, apiSpecMap); err != nil {
		t.Fatalf("cleanHandlersDir() error = %v", err)
	}

	if _, err := os.Stat(handlerPath); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("cleanHandlersDir() should remove generated handler, stat err = %v", err)
	}
	if _, err := os.Stat(testPath); err != nil {
		t.Fatalf("cleanHandlersDir() should preserve test file, stat err = %v", err)
	}
}

